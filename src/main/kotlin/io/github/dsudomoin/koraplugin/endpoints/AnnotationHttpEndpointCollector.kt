package io.github.dsudomoin.koraplugin.endpoints

import com.intellij.openapi.progress.ProgressManager
import com.intellij.openapi.project.Project
import com.intellij.psi.JavaPsiFacade
import com.intellij.psi.search.GlobalSearchScope
import com.intellij.psi.search.searches.AnnotatedElementsSearch
import io.github.dsudomoin.koraplugin.KoraAnnotations
import org.jetbrains.uast.UClass
import org.jetbrains.uast.toUElement

/**
 * Strategy A: endpoints declared with Kora annotations — @HttpController classes with
 * @HttpRoute methods ({verb, path} read from the annotations, the controller value is the
 * path prefix). Also picks up *ApiController classes generated by the OpenAPI generator
 * when generated sources are indexed; the aggregator dedupes them with the spec-based
 * strategy.
 */
object AnnotationHttpEndpointCollector {

    fun collect(project: Project): List<KoraEndpoint> {
        val annotationClass = JavaPsiFacade.getInstance(project)
            .findClass(KoraAnnotations.HTTP_CONTROLLER, GlobalSearchScope.allScope(project))
            ?: return emptyList()

        val endpoints = mutableListOf<KoraEndpoint>()
        AnnotatedElementsSearch.searchPsiClasses(annotationClass, GlobalSearchScope.projectScope(project)).forEach { psiClass ->
            ProgressManager.checkCanceled()
            val uClass = psiClass.toUElement() as? UClass ?: return@forEach
            val classFqn = psiClass.qualifiedName ?: return@forEach
            val prefix = uClass.findAnnotation(KoraAnnotations.HTTP_CONTROLLER)
                ?.let { AttributeValueResolver.resolveStringAttributeValue(it, "value") }
                .orEmpty()

            for (uMethod in uClass.methods) {
                ProgressManager.checkCanceled()
                val route = uMethod.findAnnotation(KoraAnnotations.HTTP_ROUTE) ?: continue
                val verb = AttributeValueResolver.resolveStringAttributeValue(route, "method", allowConstantNameFallback = true)
                    ?.let(::normalizeVerb)
                    ?: continue
                val routePath = AttributeValueResolver.resolveStringAttributeValue(route, "path") ?: continue

                endpoints.add(
                    KoraEndpoint(
                        verb = verb,
                        path = normalizePath(prefix, routePath),
                        operationId = null,
                        summary = null,
                        sources = setOf(EndpointSource.ANNOTATION),
                        targets = listOf(EndpointTarget.method(classFqn, uMethod.name)),
                    ),
                )
            }
        }
        return endpoints
    }
}
